  var UNITS_G = { 'yemek kaşığı': 15, 'yemek kasigi': 15, 'kaşık': 15, 'kasik': 15, 'tatlı kaşığı': 10, 'tatli kasigi': 10, 'çay kaşığı': 5, 'cay kasigi': 5, 'çay bardağı': 100, 'cay bardagi': 100, 'su bardağı': 200, 'su bardagi': 200, 'bardak': 200, 'kase': 250, 'avuç': 30, 'avuc': 30, 'fincan': 60 };

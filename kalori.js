  function parseQty(tokens) {
    var qty = null, used = -1;
    for (var i = 0; i < tokens.length; i++) {
      var t = tokens[i];
      var frac = /^(\d+)\/(\d+)$/.exec(t);
      if (frac && +frac[2]) { qty = +frac[1] / +frac[2]; used = i; break; }
      if (/^\d+([.,]\d+)?$/.test(t)) { qty = parseFloat(t.replace(',', '.')); used = i; break; }
      if (Object.prototype.hasOwnProperty.call(NUM_WORDS, t)) { qty = NUM_WORDS[t]; used = i; break; }
    }
    if (qty !== null && /^(bir)$/.test(tokens[used]) && tokens[used + 1] === 'bucuk') qty = 1.5;
    return qty;
  }

  function detectUnit(n) {
    if (/(^| )(kg|kilo|kilogram)( |$)/.test(n)) return { type: 'g', mult: 1000 };
    if (/(^| )(gr|gram|g)( |$)/.test(n) || /\d(gr|g)( |$)/.test(n)) return { type: 'g', mult: 1 };
    if (/(^| )(lt|litre|liter|l)( |$)/.test(n) || /\d(lt|l)( |$)/.test(n)) return { type: 'g', mult: 1000 };
    if (/(^| )(ml)( |$)/.test(n) || /\dml( |$)/.test(n)) return { type: 'g', mult: 1 };
    var keys = Object.keys(UNITS_G).sort(function (a, b) { return b.length - a.length; });
    for (var i = 0; i < keys.length; i++) {
      var k = norm(keys[i]);
      if (n.indexOf(k) !== -1) return { type: 'vol', word: k, grams: UNITS_G[keys[i]] };
    }
    for (var j = 0; j < COUNT_WORDS.length; j++) {
      if (n.indexOf(norm(COUNT_WORDS[j])) !== -1) return { type: 'count', word: norm(COUNT_WORDS[j]) };
    }
    return { type: 'none' };
  }

  // Tek bir yemek ifadesi -> { text, food, qty, kcal } (kcal === null: bulunamadı)
  function estimate(phrase) {
    var text = String(phrase || '').trim();
    var n = norm(text);
    var food = findFood(text);
    if (!food) return { text: text, food: null, qty: 1, kcal: null };
    // Sayı/birim ararken ad kısmını (ör. "2 dilim ekmek") yoksay: yalnızca sayısal belirteçlere bak.
    var tokens = n.split(' ');
    var qty = parseQty(tokens);
    var unit = detectUnit(n);
    var count = qty === null ? 1 : qty;
    var kcal;
    if (unit.type === 'g' && qty !== null) {
      var grams = qty * unit.mult;
      kcal = food.kcal * grams / food.grams;
      count = 1;
    } else if (unit.type === 'vol') {
      var perUnit = unit.word === norm(food.unit) ? food.kcal : food.kcal * unit.grams / food.grams;
      kcal = perUnit * count;
    } else {
      kcal = food.kcal * count;
    }
    return { text: text, food: food.name, qty: count, kcal: Math.max(0, Math.round(kcal)) };
  }

